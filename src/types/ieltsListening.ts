// IELTS-format listening tests: 4 parts, 40 questions, one recording per part.
// The shape follows the content schema of the IELTS site (ultraielts), so its
// tests can be brought over later with little more than a copy.

export interface IeltsOption {
  key: string;   // 'A', 'B', …
  text: string;
}

export interface IeltsListeningSpeaker {
  id: string;
  name: string;
  role: string;
  gender: 'female' | 'male';
  accent: 'british' | 'american';
  /** Kokoro voice used for the recording, e.g. 'af_heart'. */
  voice: string;
  /** Kokoro speed (1 = the voice's natural pace; kept ≥ 0.82 to avoid artefacts). */
  speed: number;
  /**
   * Extra slow-down after synthesis (ffmpeg atempo, pitch unchanged) for voices
   * that are still too fast at Kokoro's lowest clean speed. 1 or absent = none.
   */
  tempo?: number;
}

export type IeltsScriptSegment =
  | { kind: 'line'; id: string; speaker: string; text: string }
  /** Mid-part pause: "Before you hear the rest…, you have some time to look at questions X to Y." */
  | { kind: 'break'; preview: [number, number] };

export type IeltsAnswerKey =
  /** Typed answer; the first entry is the one shown as the key. */
  | { kind: 'text'; accepted: string[] }
  | { kind: 'choice'; key: string };

/** Where an answer is heard: a quote copied word for word from one script line. */
export interface IeltsEvidence {
  line: string;
  quote: string;
}

export interface IeltsListeningQuestion {
  number: number;
  /** mcq_single question, or the item to match (e.g. 'Café'). */
  prompt?: string;
  /** mcq_single only. */
  options?: IeltsOption[];
  /** Absent in mcq_multi groups, which are marked as a pair. */
  answer?: IeltsAnswerKey;
  evidence?: IeltsEvidence[];
  /** Turkish explanation shown after marking. */
  explanation?: string;
}

/** A line of a form, set of notes, flow-chart or sentence list. {{n}} marks the gap for question n. */
export type IeltsBlock =
  | { kind: 'heading'; text: string }
  | { kind: 'field'; label: string; value: string; example?: boolean }
  | { kind: 'bullet'; text: string; level?: 1 }
  | { kind: 'step'; text: string }
  | { kind: 'sentence'; text: string }
  | { kind: 'example'; text: string };

export interface IeltsWordLimit {
  maxWords: number;
  allowNumber: boolean;
  /** As printed in the rubric, e.g. 'ONE WORD AND/OR A NUMBER'. */
  label: string;
}

interface GroupBase {
  id: string;
  /** English rubric as printed in the exam ("Complete the form below.\nWrite …"). */
  instructions: string;
  /** Short Turkish strategy note, shown in practice mode. */
  tip?: string;
  questions: IeltsListeningQuestion[];
}

export interface IeltsGapFillGroup extends GroupBase {
  type: 'gap_fill';
  layout: 'form' | 'notes' | 'table' | 'flowchart' | 'sentences';
  title?: string;
  /** Typed answers. Absent when the gaps are filled with letters from `boxOptions`. */
  wordLimit?: IeltsWordLimit;
  boxOptions?: IeltsOption[];
  blocks?: IeltsBlock[];
  table?: { columns: string[]; rows: string[][] };
}

export interface IeltsMcqSingleGroup extends GroupBase {
  type: 'mcq_single';
}

export interface IeltsMcqMultiGroup extends GroupBase {
  type: 'mcq_multi';
  prompt: string;
  options: IeltsOption[];
  /** Any order; each correct letter is one mark. */
  answerKeys: string[];
  evidence: IeltsEvidence[];
  explanation: string;
}

export interface IeltsMatchingGroup extends GroupBase {
  type: 'matching';
  variant: 'map' | 'list';
  title?: string;
  /** Map / plan image (public path) for variant 'map'. */
  figure?: { src: string; alt: string; width: number; height: number };
  options: IeltsOption[];
  optionsTitle?: string;
}

export type IeltsQuestionGroup = IeltsGapFillGroup | IeltsMcqSingleGroup | IeltsMcqMultiGroup | IeltsMatchingGroup;

export interface IeltsListeningPart {
  number: 1 | 2 | 3 | 4;
  /** Read by the announcer: "You will hear …". */
  context: string;
  speakers: IeltsListeningSpeaker[];
  script: IeltsScriptSegment[];
  questionGroups: IeltsQuestionGroup[];
}

export interface IeltsListeningTest {
  id: string;
  title: string;
  /** Shown on the card, e.g. 'Kolay'. */
  level: string;
  difficulty: 'easy' | 'medium';
  description: string;
  parts: IeltsListeningPart[];
}

/** Timing of one recording, generated by scripts/generate-ielts-listening-audio.mjs. */
export interface IeltsAudioCue {
  /** Script line id, or 'ann-n' / 'pause-n' for announcer lines and silent reading time. */
  id: string;
  kind: 'line' | 'announcer' | 'pause';
  start: number;
  end: number;
}

export interface IeltsPartAudio {
  src: string;
  duration: number;
  cues: IeltsAudioCue[];
}

export type IeltsListeningMode = 'exam' | 'practice';

export interface IeltsListeningProgress {
  testId: string;
  format: 'ielts';
  mode: IeltsListeningMode;
  /** Everything typed or chosen so far, by question number (checked and unchecked). */
  responses: Record<number, string>;
  /** Parts whose answers have been submitted; their answers are locked. */
  submittedParts: number[];
  startedAt: Date;
  completedAt?: Date;
  /** Raw score out of 40, once all four parts are submitted. */
  rawScore?: number;
  band?: number;
}
