// Two original IELTS-format listening tests (4 parts, 40 questions each),
// written for a student moving from band 4.5–5 towards 6.5.
//
// They follow the real exam's format (question types, rubrics, announcer,
// reading time, answers heard in order) but are deliberately easier than a
// real paper:
//   - slower recordings (about 150–165 words per minute in conversation),
//   - everyday vocabulary, and answers that are common, easy-to-spell words,
//   - fewer distractors, and when there is one it is corrected clearly
//     ("I thought… but actually…"),
//   - more time between answers and clear signposting in Parts 2 and 4.
// Test 1 is the easier of the two; Test 2 uses more paraphrase and more
// distractors and is closer to the real exam.
//
// Every evidence quote is copied word for word from its script line and every
// typed answer appears in the script; tests/ielts-listening-content.test.mjs
// checks both. After editing a script, re-render the audio with
// scripts/generate-ielts-listening-audio.mjs.

const L = (id: string, speaker: string, text: string): IeltsScriptSegment => ({ kind: 'line', id, speaker, text });
const BREAK = (from: number, to: number): IeltsScriptSegment => ({ kind: 'break', preview: [from, to] });
const text = (...accepted: string[]): IeltsAnswerKey => ({ kind: 'text', accepted });
const choice = (key: string): IeltsAnswerKey => ({ kind: 'choice', key });
const ev = (line: string, quote: string): IeltsEvidence => ({ line, quote });
const abc = (a: string, b: string, c: string): IeltsOption[] => [
  { key: 'A', text: a },
  { key: 'B', text: b },
  { key: 'C', text: c },
];
const lettersUpTo = (last: string): IeltsOption[] =>
  'ABCDEFGHIJ'.slice(0, 'ABCDEFGHIJ'.indexOf(last) + 1).split('').map(key => ({ key, text: key }));

