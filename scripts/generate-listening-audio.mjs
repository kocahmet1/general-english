// Run explicitly: node --env-file=.env scripts/generate-listening-audio.mjs
// Requires OPENAI_API_KEY and ffmpeg (or Python's imageio_ffmpeg package).
import { readFile, writeFile, mkdir, access } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import ts from 'typescript';
import OpenAI from 'openai';

const root = fileURLToPath(new URL('../', import.meta.url));
const source = await readFile(path.join(root, 'src/data/listeningContent.ts'), 'utf8');
const { outputText } = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext } });
const { listeningContent } = await import(`data:text/javascript;base64,${Buffer.from(outputText).toString('base64')}`);
const client = new OpenAI({ maxRetries: 2, timeout: 120000 });
const outputDir = path.join(root, 'public/audio/toefl');
const cacheDir = path.join(root, '.tools/listening-audio-cache');
await mkdir(outputDir, { recursive: true });
await mkdir(cacheDir, { recursive: true });
let ffmpeg = process.env.FFMPEG_PATH || 'ffmpeg';
try { execFileSync(ffmpeg, ['-version'], { stdio: 'ignore' }); }
catch { ffmpeg = execFileSync('python', ['-c', 'import imageio_ffmpeg; print(imageio_ffmpeg.get_ffmpeg_exe())'], { encoding: 'utf8' }).trim(); }

const manifest = {};
for (const passage of listeningContent) {
  const buffers = [];
  const turns = [];
  let elapsed = 0;
  for (const [index, turn] of passage.turns.entries()) {
    const hash = createHash('sha256').update(JSON.stringify(['tts-1', turn.voice, turn.text, 0.94])).digest('hex');
    const cache = path.join(cacheDir, `${hash}.pcm`);
    let pcm;
    try { await access(cache); pcm = await readFile(cache); }
    catch {
      const result = await client.audio.speech.create({ model: 'tts-1', voice: turn.voice, input: turn.text, response_format: 'pcm', speed: 0.94 });
      pcm = Buffer.from(await result.arrayBuffer());
      if (!pcm.length || pcm.length % 2) throw new Error(`Invalid PCM: ${passage.id}, turn ${index}`);
      await writeFile(cache, pcm);
    }
    const duration = pcm.length / (24000 * 2);
    turns.push({ startTime: Number(elapsed.toFixed(3)), endTime: Number((elapsed + duration).toFixed(3)) });
    buffers.push(pcm);
    elapsed += duration;
    if (index < passage.turns.length - 1) {
      const pauseSeconds = passage.section === 'conversation' ? 0.3 : 0.55;
      buffers.push(Buffer.alloc(24000 * 2 * pauseSeconds));
      elapsed += pauseSeconds;
    }
    console.log(`${passage.id}: ${index + 1}/${passage.turns.length} (${turn.voice})`);
  }
  const recording = path.join(outputDir, `${passage.id}.mp3`);
  execFileSync(ffmpeg, ['-hide_banner', '-loglevel', 'error', '-y', '-f', 's16le', '-ar', '24000', '-ac', '1', '-i', 'pipe:0', '-codec:a', 'libmp3lame', '-b:a', '96k', recording], { input: Buffer.concat(buffers), maxBuffer: 16 * 1024 * 1024 });
  manifest[passage.id] = { duration: Number(elapsed.toFixed(3)), turns };
  console.log(`Saved ${passage.id}: ${Math.round(elapsed)} seconds`);
}
await writeFile(path.join(root, 'src/data/listeningAudioManifest.ts'), `// Generated by scripts/generate-listening-audio.mjs.\nexport const listeningAudioManifest: Record<string, { duration: number; turns: { startTime: number; endTime: number }[] }> = ${JSON.stringify(manifest, null, 2)};\n`);
console.log('All six recordings and timing metadata are ready.');
